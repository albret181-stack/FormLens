import {execFileSync} from 'node:child_process';
import {mkdtemp,symlink,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
const {version}=JSON.parse(await readFile('package.json','utf8'));
const app=path.resolve('../build/FormLens-darwin-arm64/FormLens.app');
const run=(cmd,args)=>execFileSync(cmd,args,{stdio:'inherit'});
run('codesign',['--force','--deep','--sign','-',app]);
run('codesign',['--verify','--deep','--strict',app]);
const staging=await mkdtemp(path.resolve('../build/dmg-'));
run('ditto',[app,path.join(staging,'FormLens.app')]);
await symlink('/Applications',path.join(staging,'Applications'));
await writeFile(path.join(staging,'Установка.txt'),'Перенесите FormLens.app в Applications (Программы).\nПеред заменой старой версии сохраните разбор и завершите FormLens.\nПроекты находятся в профиле приложения и не включены в этот образ.\nСборка экспериментальная, без Apple Developer ID и нотарификации.\n');
const dmg=path.resolve(`../FormLens-${version}-arm64.dmg`);
run('hdiutil',['create','-volname',`FormLens ${version}`,'-srcfolder',staging,'-ov','-format','UDZO',dmg]);
run('hdiutil',['verify',dmg]);
const checksum=createHash('sha256').update(await readFile(dmg)).digest('hex');
await writeFile(path.resolve('../SHA256SUMS.txt'),`${checksum}  ${path.basename(dmg)}\n`);
console.log('DMG готов:',dmg);
