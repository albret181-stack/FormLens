import {execFileSync,spawnSync} from 'node:child_process';
import {mkdtemp,symlink,writeFile,readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {makeUpdateFeed} from './update-feed.mjs';
const {version}=JSON.parse(await readFile('package.json','utf8'));
const app=path.resolve('../build/FormLens-darwin-arm64/FormLens.app');
const run=(cmd,args)=>execFileSync(cmd,args,{stdio:'inherit'});
const signed=!!process.env.FORMLENS_SIGN_IDENTITY;
if(process.env.FORMLENS_REQUIRE_SIGNED_RELEASE==='1'&&!signed)throw Error('Подписанный выпуск требует Developer ID Application.');
if(!signed)run('codesign',['--force','--deep','--sign','-',app]);
run('codesign',['--verify','--deep','--strict',app]);
const artifacts=[];
if(signed){
 const details=spawnSync('codesign',['-dv','--verbose=4',app],{encoding:'utf8'});
 const team=/^TeamIdentifier=([A-Z0-9]{10})$/m.exec(details.stderr||'')?.[1];
 if(details.status!==0||!team||team!==process.env.APPLE_TEAM_ID)throw Error('Подпись приложения не соответствует APPLE_TEAM_ID.');
 for(const key of ['APPLE_ID','APPLE_APP_SPECIFIC_PASSWORD','APPLE_TEAM_ID'])if(!process.env[key])throw Error(`Не настроено ${key}`);
 const submitZip=path.resolve('../build/FormLens-notarization.zip');
 run('ditto',['-c','-k','--sequesterRsrc','--keepParent',app,submitZip]);
 run('xcrun',['notarytool','submit',submitZip,'--apple-id',process.env.APPLE_ID,'--password',process.env.APPLE_APP_SPECIFIC_PASSWORD,'--team-id',process.env.APPLE_TEAM_ID,'--wait']);
 run('xcrun',['stapler','staple',app]);
 run('xcrun',['stapler','validate',app]);
 run('codesign',['--verify','--deep','--strict',app]);
 const zip=path.resolve(`../FormLens-${version}-arm64.zip`);
 run('ditto',['-c','-k','--sequesterRsrc','--keepParent',app,zip]);
 const feedPath=path.resolve(`../FormLens-${version}-arm64-update.json`);
 await writeFile(feedPath,JSON.stringify(await makeUpdateFeed({version,zipPath:zip}),null,2)+'\n');
 artifacts.push(zip,feedPath);
}
const staging=await mkdtemp(path.resolve('../build/dmg-'));
run('ditto',[app,path.join(staging,'FormLens.app')]);
await symlink('/Applications',path.join(staging,'Applications'));
await writeFile(path.join(staging,'Установка.txt'),`Перенесите FormLens.app в Applications (Программы).\nПервый переход с прежней версии выполняется вручную.\n${signed?'Следующие подписанные выпуски устанавливаются через колокольчик.':'Локальная экспериментальная сборка без автоустановки.'}\nРазборы хранятся отдельно в профиле приложения.\n`);
const dmg=path.resolve(`../FormLens-${version}-arm64.dmg`);
run('hdiutil',['create','-volname',`FormLens ${version}`,'-srcfolder',staging,'-ov','-format','UDZO',dmg]);
run('hdiutil',['verify',dmg]);artifacts.push(dmg);
const sums=await Promise.all(artifacts.map(async file=>`${createHash('sha256').update(await readFile(file)).digest('hex')}  ${path.basename(file)}`));
await writeFile(path.resolve('../SHA256SUMS.txt'),sums.join('\n')+'\n');
console.log('Артефакты готовы:',artifacts.map(file=>path.basename(file)).join(', '));
